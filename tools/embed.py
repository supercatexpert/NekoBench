#!/usr/bin/env python3
"""Embed text assets into a C header as NUL-terminated char arrays.

usage: embed.py OUTPUT.h INPUT...   (symbol: nb_asset_<basename with . -> _>)
"""
import os
import re
import sys


def main():
    out, inputs = sys.argv[1], sys.argv[2:]
    lines = ["/* Generated by tools/embed.py - do not edit. */", "#pragma once", ""]
    for path in inputs:
        name = "nb_asset_" + re.sub(r"[^0-9A-Za-z]", "_", os.path.basename(path))
        with open(path, "rb") as f:
            data = f.read() + b"\0"
        lines.append(f"static const char {name}[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
